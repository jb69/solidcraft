#!/usr/bin/env python3
"""Generate crates/plugin-foil/src/tables_gen.rs: the FeatureScript's tabulated sections.

    python3 crates/plugin-foil/gen/gen_tables.py <foil_design_bN.fs> > crates/plugin-foil/src/tables_gen.rs && cargo fmt -p solidcraft-plugin-foil
"""
import re
import sys

FOIL = ["E817_UPPER", "E817_LOWER", "E818_UPPER", "E818_LOWER", "NACA63412_UPPER", "NACA63412_LOWER", "CLARKY_UPPER", "CLARKY_LOWER",
        "MRC16_UPPER", "MRC16_LOWER", "MH18_UPPER", "MH18_LOWER", "H105_UPPER", "H105_LOWER"]


def const(src, name):
    m = re.search(r"^const %s\s*=\s*(\[.*?\]);" % name, src, re.S | re.M)
    body = re.sub(r"//[^\n]*", "", m.group(1))
    body = re.sub(r"vector\(([^,]+),\s*([^)]+)\)", r"[\1, \2]", body)
    return eval(body)


def num(x):
    return repr(float(x))


def main():
    foil = open(sys.argv[1]).read()
    print("// Generated by crates/plugin-foil/gen/gen_tables.py from the Onshape FeatureScript: do not edit.")
    print("#![allow(clippy::all)]\n")
    for n in FOIL:
        v = const(foil, n)
        print("pub static %s: &[[f64; 2]] = &[%s];" % (n, ", ".join("[%s, %s]" % (num(a), num(b)) for a, b in v)))


main()
