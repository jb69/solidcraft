#!/usr/bin/env python3
"""Generate crates/plugin-foil/src/tables_gen.rs: the FeatureScript's tabulated sections and B-series tables.

    python3 crates/plugin-foil/gen/gen_tables.py <foil_design_bN.fs> <bseries_blade_bN.fs> > crates/plugin-foil/src/tables_gen.rs && cargo fmt -p solidcraft-plugin-foil
"""
import re
import sys

FOIL = ["E817_UPPER", "E817_LOWER", "E818_UPPER", "E818_LOWER", "NACA63412_UPPER", "NACA63412_LOWER", "CLARKY_UPPER", "CLARKY_LOWER",
        "MRC16_UPPER", "MRC16_LOWER", "MH18_UPPER", "MH18_LOWER", "H105_UPPER", "H105_LOWER"]
PROP = ["TABLE_STATIONS", "K_Z3", "K_Z4", "AC_Z3", "AC_Z4", "BC_Z3", "BC_Z4", "P_STATIONS", "V1_TABLE", "V2_TABLE", "NACA16_THICKNESS",
        "NACA16_CAMBER", "NACA66_THICKNESS", "NACA66_CAMBER", "ARC_SHAPE", "NACA4_THICKNESS", "CLARKY_THICKNESS", "CLARKY_CAMBER",
        "YS920_THICKNESS", "YS920_CAMBER", "E817_THICKNESS", "E817_CAMBER", "ELLIPSE_THICKNESS"]


def const(src, name):
    m = re.search(r"^const %s\s*=\s*(\[.*?\]);" % name, src, re.S | re.M)
    body = re.sub(r"//[^\n]*", "", m.group(1))
    body = re.sub(r"vector\(([^,]+),\s*([^)]+)\)", r"[\1, \2]", body)
    return eval(body)


def num(x):
    return repr(float(x))


def main():
    foil, prop = open(sys.argv[1]).read(), open(sys.argv[2]).read()
    print("// Generated by crates/plugin-foil/gen/gen_tables.py from the Onshape FeatureScript: do not edit.")
    print("#![allow(clippy::all)]\n")
    for n in FOIL:
        v = const(foil, n)
        print("pub static %s: &[[f64; 2]] = &[%s];" % (n, ", ".join("[%s, %s]" % (num(a), num(b)) for a, b in v)))
    for n in PROP:
        v = const(prop, n)
        if isinstance(v[0], list):
            print("pub static PROP_%s: &[[f64; %d]] = &[%s];" % (n, len(v[0]), ", ".join("[%s]" % ", ".join(num(x) for x in r) for r in v)))
        else:
            print("pub static PROP_%s: &[f64] = &[%s];" % (n, ", ".join(num(x) for x in v)))


main()
